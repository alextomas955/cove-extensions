#!/usr/bin/env node
// Asserts every named import of a host-served package, in every extension UI, exists in the module the
// host actually serves.
//
// These packages are host import-map externals (shared/ui-shared/vite/createExtensionViteConfig.ts),
// so the bundle never carries them: at runtime the name is resolved against the host's generated re-export
// shim, not against the version installed here for typechecking. Those two can diverge - lucide renames
// icons between releases, and react-query adds and removes exports across minors - so a name that exists
// only in the local copy typechecks, builds, and passes every other check, then throws an ESM SyntaxError
// at load that kills the whole bundle, so every surface of the extension renders "component not found".
//
// This is what makes a locally installed copy of a host-served package safe. The local version is for
// types and the test runner; the names the shipped bundle depends on are checked against the host's.
//
// The host's list is authoritative and generated from its own package exports, so it is read from a
// Cove checkout rather than mirrored here. The file is generated by `npm run generate:extension-runtime`
// in that checkout's ui/ directory. With no ../cove sibling the check skips loudly. A checkout named
// through COVE_REPO must hold the file, which is how ci.yml makes the skip impossible in CI.

import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..");
const coveRepo = process.env.COVE_REPO ?? path.resolve(repoRoot, "../cove");
// Every host-served package an extension imports by name. A package absent from this list is simply
// unchecked, so adding an import of a new host-served package means adding it here.
const CHECKED_PACKAGES = ["lucide-react", "react-query"];

const shimDir = path.join(coveRepo, "ui/src/generated/extensions/runtime/v1");

// Keyed by the specifier a source file imports from, which is the bare package name for both of these.
const hostExports = new Map();
for (const pkg of CHECKED_PACKAGES) {
  const shim = path.join(shimDir, `${pkg}.ts`);
  if (!existsSync(shim)) {
    if (process.env.COVE_REPO) {
      console.error(
        `check-host-imports: COVE_REPO names ${coveRepo}, which holds no host shim at ${shim}. Run "npm run generate:extension-runtime" in its ui/ directory.`,
      );
      process.exit(1);
    }
    console.log(
      `check-host-imports: SKIPPED - no host shim at ${shim} (set COVE_REPO or add a ../cove sibling)`,
    );
    process.exit(0);
  }
  const names = new Set(
    [...readFileSync(shim, "utf8").matchAll(/^export const (\w+) =/gm)].map((m) => m[1]),
  );
  // The shim is named for the package; react-query's is imported under the @tanstack scope.
  hostExports.set(pkg === "react-query" ? "@tanstack/react-query" : pkg, names);
}

function* sources(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) yield* sources(full);
    else if (/\.tsx?$/.test(name)) yield full;
  }
}

const uiRoots = readdirSync(path.join(repoRoot, "extensions"), {
  withFileTypes: true,
})
  .filter((e) => e.isDirectory())
  .flatMap((e) =>
    readdirSync(path.join(repoRoot, "extensions", e.name, "src"), {
      withFileTypes: true,
    })
      .filter((u) => u.isDirectory() && u.name.endsWith(".Ui"))
      .map((u) => path.join(repoRoot, "extensions", e.name, "src", u.name, "src")),
  )
  .filter(existsSync);

let checked = 0;
const missing = [];
for (const root of uiRoots) {
  for (const file of sources(root)) {
    const text = readFileSync(file, "utf8");
    for (const [specifierName, names] of hostExports) {
      const pattern = new RegExp(
        `import\\s+(type\\s+)?\\{([^}]*)\\}\\s*from\\s*["']${specifierName.replaceAll("/", "\\/")}["']`,
        "g",
      );
      for (const m of text.matchAll(pattern)) {
        // A type-only import is erased before the module is ever fetched, so it never reaches the host
        // module and cannot fail at load - in either the whole-clause or the inline-specifier form.
        if (m[1]) continue;
        for (const clause of m[2].split(",")) {
          const specifier = clause.trim();
          if (specifier.startsWith("type ")) continue;
          const name = specifier.split(/\sas\s/)[0].trim();
          if (!name) continue;
          checked++;
          if (!names.has(name)) {
            missing.push({ file: path.relative(repoRoot, file), name, from: specifierName });
          }
        }
      }
    }
  }
}

if (missing.length > 0) {
  console.error(`check-host-imports: ${missing.length} import(s) the host does not export:\n`);
  for (const { file, name, from } of missing) {
    const alt = [...hostExports.get(from)]
      .filter((e) => e.includes(name.replace(/Icon$/, "")) || name.includes(e))
      .slice(0, 3);
    const offers = alt.length ? ` - the host offers: ${alt.join(", ")}` : "";
    console.error(`  ${file}\n    "${name}" is absent from the host's ${from}${offers}`);
  }
  console.error(
    `\nThis would fail the whole bundle at load with an ESM SyntaxError, not just the one name.`,
  );
  process.exit(1);
}

const summary = [...hostExports].map(([name, names]) => `${name} ${String(names.size)}`).join(", ");
console.log(
  `check-host-imports: OK (${checked} imports across ${uiRoots.length} UI bundles; host exports: ${summary})`,
);
